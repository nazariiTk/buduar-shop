CREATE TABLE IF NOT EXISTS public.customers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id integer NOT NULL UNIQUE,
  customer_code text,
  name text NOT NULL,
  phone text,
  address text,
  discount_percent numeric,
  total_spent numeric,
  bonus numeric,
  telegram_id bigint,
  is_active boolean NOT NULL DEFAULT true,
  source_updated_at timestamptz,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS customers_phone_idx
  ON public.customers (phone);

CREATE INDEX IF NOT EXISTS customers_name_idx
  ON public.customers (name);

CREATE TABLE IF NOT EXISTS public.customer_sales (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id integer NOT NULL UNIQUE,
  customer_source_id integer NOT NULL REFERENCES public.customers(source_id),
  document_date date,
  document_time timestamptz,
  document_number integer,
  office_id integer,
  total_amount numeric,
  discount_percent numeric,
  user_id text,
  card_id integer,
  archived boolean NOT NULL DEFAULT false,
  paid_by_card boolean NOT NULL DEFAULT false,
  fiscal_id text,
  fiscal_number text,
  memo text,
  source_guid uuid,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS customer_sales_customer_idx
  ON public.customer_sales (customer_source_id);

CREATE INDEX IF NOT EXISTS customer_sales_date_idx
  ON public.customer_sales (document_date DESC);

CREATE TABLE IF NOT EXISTS public.customer_sale_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id integer NOT NULL UNIQUE,
  sale_source_id integer NOT NULL REFERENCES public.customer_sales(source_id) ON DELETE CASCADE,
  article_id integer NOT NULL,
  quantity numeric,
  unit_price numeric,
  discount_percent numeric,
  serial_number text,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS customer_sale_items_sale_idx
  ON public.customer_sale_items (sale_source_id);

CREATE INDEX IF NOT EXISTS customer_sale_items_article_idx
  ON public.customer_sale_items (article_id);
